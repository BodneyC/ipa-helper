// Commits the maintainer's picks as the app's symbol clips (M4.3).
// Usage: pnpm audio:select path/to/picks.json
// Copies each chosen render (byte for byte: what was heard is what ships) into
// src/assets/audio/symbols/<id>.opus and writes manifest.json beside them.
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { parseRendered, resolvePicks } from './clips';
import type { ClipEntry } from './clips';
import { CACHE, ENCODING, ROOT, RUNTIME, sha256, VOICE } from './voice';

const picksPath = process.argv[2];
if (picksPath === undefined) throw new Error('usage: pnpm audio:select path/to/picks.json');

const CANDIDATES = join(CACHE, 'symbol-clips');
const rendered = parseRendered(
  JSON.parse(readFileSync(join(CANDIDATES, 'candidates.json'), 'utf8')),
);
const picks = resolvePicks(JSON.parse(readFileSync(picksPath, 'utf8')));
if (!picks.ok) throw new Error(`picks.json:\n  ${picks.problems.join('\n  ')}`);

const OUT = join(ROOT, 'src', 'assets', 'audio', 'symbols');
mkdirSync(OUT, { recursive: true });
for (const file of readdirSync(OUT)) {
  if (file.endsWith('.opus')) rmSync(join(OUT, file));
}

const clips: Record<string, ClipEntry> = {};
for (const pick of picks.chosen) {
  const render = rendered.find((r) => r.id === pick.id && r.frame === pick.frame);
  if (render?.text !== pick.text || render.lengthScale !== pick.lengthScale) {
    throw new Error(
      `${pick.id}/${pick.frame}: render is missing or stale; re-run pnpm audio:candidates --only ${pick.id}`,
    );
  }
  const bytes = readFileSync(join(CANDIDATES, render.file));
  if (sha256(bytes) !== render.sha256)
    throw new Error(`${render.file}: changed since it was rendered`);
  copyFileSync(join(CANDIDATES, render.file), join(OUT, `${pick.id}.opus`));
  clips[pick.id] = {
    frame: pick.frame,
    text: pick.text,
    lengthScale: pick.lengthScale,
    sha256: render.sha256,
  };
}

const manifest = {
  $comment:
    'Generated by `pnpm audio:select` (scripts/audio, M4.3, ADR-0009). Do not edit by hand.',
  voice: {
    name: VOICE.name,
    source: `rhasspy/piper-voices@${VOICE.revision}`,
    modelSha256: VOICE.model.sha256,
    configSha256: VOICE.config.sha256,
  },
  runtime: RUNTIME,
  encoding: `Ogg Opus (${ENCODING.codec}), mono, ${String(ENCODING.sampleRate)} Hz, ${ENCODING.bitrate}bit/s`,
  clips,
};
writeFileSync(join(OUT, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`${String(picks.chosen.length)} clips written to ${OUT}`);
