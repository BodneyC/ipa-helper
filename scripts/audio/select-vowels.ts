// Commits the maintainer's vowel picks as the app's vowel clips.
// Usage: pnpm audio:select-vowels path/to/vowel-picks.json
// Copies each chosen render (byte for byte: what was heard is what ships) into
// src/assets/audio/symbols/<id>.opus and updates its manifest entry. Vowels
// picked `current`, or not picked, keep their clip.
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { CACHE, ROOT, sha256 } from './voice';
import { chosenRenders, parseVowelPicks, parseVowelRenders } from './vowels';

const picksPath = process.argv[2];
if (picksPath === undefined) {
  throw new Error('usage: pnpm audio:select-vowels path/to/vowel-picks.json');
}

const CANDIDATES = join(CACHE, 'vowel-clips');
const OUT = join(ROOT, 'src', 'assets', 'audio', 'symbols');
const picks = parseVowelPicks(JSON.parse(readFileSync(picksPath, 'utf8')));
if (!picks.ok) throw new Error(`vowel-picks.json:\n  ${picks.problems.join('\n  ')}`);
const rendered = parseVowelRenders(
  JSON.parse(readFileSync(join(CANDIDATES, 'vowels.json'), 'utf8')),
);

const manifestPath = join(OUT, 'manifest.json');
const manifest: unknown = JSON.parse(readFileSync(manifestPath, 'utf8'));
const clips: unknown =
  typeof manifest === 'object' && manifest !== null ? Reflect.get(manifest, 'clips') : undefined;
if (
  typeof manifest !== 'object' ||
  manifest === null ||
  typeof clips !== 'object' ||
  clips === null
) {
  throw new Error(`${manifestPath} has no clips`);
}

for (const render of chosenRenders(picks.picks, rendered)) {
  const bytes = readFileSync(join(CANDIDATES, render.file));
  copyFileSync(join(CANDIDATES, render.file), join(OUT, `${render.id}.opus`));
  Reflect.set(clips, render.id, {
    frame: `vowel-${render.key}`,
    text: render.text,
    lengthScale: render.lengthScale,
    sha256: sha256(bytes),
  });
  console.log(`${render.id.padEnd(18)} ${render.key.padEnd(12)} ${render.text}`);
}
Reflect.set(
  manifest,
  '$comment',
  'Generated by `pnpm audio:select`, with vowels re-picked by `pnpm audio:select-vowels` (frames `vowel-…`) (scripts/audio, M4.3, ADR-0009). Do not edit by hand.',
);
writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
