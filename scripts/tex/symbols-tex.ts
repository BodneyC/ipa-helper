// Builds the LaTeX document the CI TeX job compiles (M6.4, FR-22, ADR-0008):
// every symbol's TIPA, as the app writes it, inside the macro the settings
// dialog suggests. pdflatex is the source of truth for "the encoding is
// correct". Pure, so it can be unit-tested; write-tex.ts writes the file.
import { SYMBOLS } from '../../src/domain/inventory/index';
import { symbolId } from '../../src/domain/inventory/symbol-id';
import type { SymbolId } from '../../src/domain/inventory/symbol-id';
import type { DisplayOptions } from '../../src/domain/serialise/serialiser';
import { createTipaSerialiser } from '../../src/domain/serialise/tipa';
import { wordFromIds } from '../../src/domain/word/word';

const NARROW: DisplayOptions = { slashes: false, rDisplay: 'narrow', tieBars: false };
const BASES = [symbolId('n'), symbolId('e')];

/** The TIPA the app writes for a word of these symbols. */
const tipaOf = (ids: readonly SymbolId[], options: DisplayOptions = NARROW): string =>
  createTipaSerialiser(options).serialise(wordFromIds(ids));

/** One labelled sample, as a table row: the ID(s), then `\ipa{…}`. */
const row = (label: string, tipa: string) => `\\texttt{${label}} & \\ipa{${tipa}} \\\\`;

/** Samples written as a run of `\ipa{…}` calls, wrapped by TeX. */
const run = (words: readonly (readonly SymbolId[])[], options: DisplayOptions = NARROW) =>
  words.map((ids) => `\\ipa{${tipaOf(ids, options)}}`).join(' ');

const TIED: DisplayOptions = { ...NARROW, tieBars: true };

/**
 * The whole document (M6.4):
 * - every symbol on its own, the broad British r (Q-3), and each affricate
 *   under a tie bar (M6.5), alone and next to every symbol;
 * - every diacritic on a consonant and a vowel, and every pair of diacritics
 *   stacked on one base;
 * - every ordered pair of symbols, so every boundary the serialiser can write
 *   (a `{}` separator, a braced macro before a letter, a wrap around a
 *   command) is compiled at least once;
 * - the Q-2 variant with slashes inside the argument.
 *
 * `\tracinglostchars=3` turns a glyph missing from the TIPA fonts into an
 * error, so a mistyped shortcut can't pass silently.
 */
export const symbolsTex = (): string => {
  const ids = SYMBOLS.map((s) => s.id);
  const marks = SYMBOLS.filter((s) => s.category === 'diacritic').map((s) => s.id);
  const affricates = SYMBOLS.filter((s) => s.category === 'affricate').map((s) => s.id);
  const tied = affricates
    .map((a) =>
      run(
        ids.flatMap((b) => [
          [a, b],
          [b, a],
        ]),
        TIED,
      ),
    )
    .join('\n\n');
  const rows = [
    ...SYMBOLS.map((s) => row(s.id, tipaOf([s.id]))),
    ...SYMBOLS.filter((s) => s.ipa === 'ɹ').map((s) =>
      row(`${s.id} (broad)`, tipaOf([s.id], { ...NARROW, rDisplay: 'broad' })),
    ),
    ...affricates.map((id) => row(`${id} (tie bar)`, tipaOf([id], TIED))),
    ...marks.flatMap((mark) => BASES.map((base) => row(`${base}+${mark}`, tipaOf([base, mark])))),
  ].join('\n');
  const stacked = run(marks.flatMap((a) => marks.map((b) => [symbolId('n'), a, b])));
  const pairs = ids.map((a) => run(ids.map((b) => [a, b]))).join('\n\n');
  const slashed = createTipaSerialiser({ ...NARROW, slashes: true }).serialise(
    wordFromIds(ids.slice(0, 3)),
  );
  return `% Generated by scripts/tex/write-tex.ts (M6.4). Do not edit.
\\documentclass{article}
\\usepackage{tipa}
\\usepackage{longtable}
\\tracinglostchars=3
% The definition the settings dialog suggests (FR-21): newCommandFor('ipa', false).
\\newcommand{\\ipa}[1]{\\textipa{/#1/}}
% Q-2: for slashes inside the argument, newCommandFor('ipa', true).
\\newcommand{\\ipaInside}[1]{\\textipa{#1}}
\\begin{document}
\\section*{Symbols, variants and diacritics}
\\begin{longtable}{ll}
${rows}
\\end{longtable}
\\section*{Slashes inside the argument (Q-2)}
\\ipaInside{${slashed}}
\\section*{Stacked diacritics}
\\raggedright
${stacked}
\\section*{Tie-bar affricates next to every symbol}
${tied}
\\section*{Every ordered pair of symbols}
${pairs}
\\end{document}
`;
};
